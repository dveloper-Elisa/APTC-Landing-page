                    <h2>ABOUT AGRO PROCESSING INDUSTRIES Ltd (API)</h2>
                    <p>RAPI is engaged in crop production with particular focus
                        on maize, beans and soya beans.</p>

                    <p>For the past three years, the company has been producing
                        hybrid seeds and Open Pollinated Varieties (OPVs) for
                        maize, beans and soya beans as well as importation of
                        fertilizers.</p>

                    <p>API is located in Gabiro, Nyagatare District and has a
                        separate management team that runs its day-to-day
                        business activities. API is a conduit through which APTC
                        contributes to the National Agenda of sustainable food
                        security in terms of Producing affordable Agri-inputs ie
                        improved seeds and fertilizers for import substitution.

                    </p>
                    <p>Rwanda spends Rwf5 billion on seed imports every year of
                        which maize accounts for 75 per cent of the country’s
                        seed imports. The country imports 3,000 tonnes of maize
                        every year and a combined 1000 tonnes of wheat and
                        soya.</p>
                    <p>However, Rwanda’s annual maize seed imports are set to
                        drop drastically thanks to a new private sector
                        partnership that seeks to produce hybrid seed locally
                        and address challenges of delays in quality seed
                        distribution to farmers.</p>
                    <p>The partnership between Agro-Processing Industries (API),
                        One Acre Fund and Western Seed Company (WSC) aims to
                        make Rwanda self-reliant in seeds and be able to export
                        the surplus. There are many benefits from producing
                        seeds locally ; first, they are more affordable, they
                        can be available on time and avoid bureaucracy in
                        procurement for seed import processes.</p>
                    <p>It also helps in avoiding deterioration of seeds due to
                        long distances, and defaults such as disease that seed
                        can carry from the country of origin as well as
                        unsuitability of seed to the land it is going to be
                        grown. API will be able to supply up to 600tonnes of
                        hybrid maize to farmers in 2019.</p>

